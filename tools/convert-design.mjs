#!/usr/bin/env node
// Converts the Jobseeker design canvas (its project/*.dc.html artboards) into
// pages of this Vite + React site.
//
//   node tools/convert-design.mjs <design-dir> [<images-dir>]
//
// <design-dir> holds the canvas files as downloaded (project/canvas.json,
// project/*.dc.html, project/ds/...). <images-dir> holds the canvas images,
// named <asset-id>.<ext> (defaults to <design-dir>).
//
// For each artboard it writes:
//   src/pages/<Name>/Page.jsx    the artboard's logic class + its template as JSX
//   src/pages/<Name>/styles.css  the artboard's own stylesheet
//   src/pages/<Name>/main.jsx    the page entry
//   <route>/index.html           the HTML document Vite builds
// plus src/routes.json, src/lib/assets.js, public/images/* and src/ds/jobseeker/*.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDocument } from 'htmlparser2';
import * as prettier from 'prettier';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const designDir = process.argv[2];
if (!designDir) {
  console.error('usage: node tools/convert-design.mjs <design-dir> [<images-dir>]');
  process.exit(1);
}
const imagesDir = process.argv[3] || designDir;
const projectDir = path.join(designDir, 'project');
const canvas = JSON.parse(fs.readFileSync(path.join(projectDir, 'canvas.json'), 'utf8'));

// ---------------------------------------------------------------- routes
const kebab = (s) =>
  s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1-$2').toLowerCase();

function routeFor(name) {
  if (name === 'Main') return '/';
  const m = name.match(/^(.*?)2$/);
  if (m) return m[1] === 'Home' ? '/v2/' : `/v2/${kebab(m[1])}/`;
  return `/${kebab(name)}/`;
}

const boards = canvas.order.map((file) => {
  const name = file.replace(/\.dc\.html$/, '');
  return { file, name, route: routeFor(name), title: canvas.boards[file]?.title || name };
});
const routeByFile = Object.fromEntries(boards.map((b) => [b.file, b.route]));

function rewriteLinks(s) {
  return s.replace(/\b([A-Za-z0-9_]+\.dc\.html)(#[\w-]*)?/g, (m, file, hash) =>
    routeByFile[file] ? routeByFile[file] + (hash || '') : m,
  );
}

// ---------------------------------------------------------------- assets
const ASSETS = {};
fs.mkdirSync(path.join(ROOT, 'public/images'), { recursive: true });
for (const f of fs.readdirSync(imagesDir)) {
  const m = f.match(/^([0-9a-f]{32})\.(png|webp|svg|jpe?g|gif)$/);
  if (!m) continue;
  ASSETS[m[1]] = f;
  fs.copyFileSync(path.join(imagesDir, f), path.join(ROOT, 'public/images', f));
}
fs.writeFileSync(
  path.join(ROOT, 'src/lib/assets.js'),
  '// Generated by tools/convert-design.mjs: design asset id -> file in public/images.\n' +
    `export const ASSETS = ${JSON.stringify(ASSETS, null, 2)};\n`,
);
const rewriteBlobs = (s) =>
  s.replace(/\/_blob\/([0-9a-f]{32})/g, (m, id) => (ASSETS[id] ? '/images/' + ASSETS[id] : m));

// ---------------------------------------------------------------- design system
const dsSrc = path.join(projectDir, 'ds/jobseeker');
const dsOut = path.join(ROOT, 'src/ds/jobseeker');
fs.mkdirSync(dsOut, { recursive: true });
for (const f of ['tokens.css', 'components/bundle.css', 'components/bundle.js', 'components/index.d.ts']) {
  fs.mkdirSync(path.dirname(path.join(dsOut, f)), { recursive: true });
  fs.copyFileSync(path.join(dsSrc, f), path.join(dsOut, f));
}

// ---------------------------------------------------------------- JSX emitter
const BOOL_ATTRS = new Set([
  'disabled', 'checked', 'selected', 'required', 'open', 'hidden', 'readonly', 'multiple',
  'autofocus', 'autoplay', 'loop', 'muted', 'playsinline', 'controls', 'novalidate', 'async',
  'defer', 'allowfullscreen', 'inert', 'reversed', 'default', 'formnovalidate', 'itemscope',
]);
const ATTR_MAP = {
  class: 'className', for: 'htmlFor', tabindex: 'tabIndex', readonly: 'readOnly',
  maxlength: 'maxLength', minlength: 'minLength', colspan: 'colSpan', rowspan: 'rowSpan',
  autocomplete: 'autoComplete', autofocus: 'autoFocus', novalidate: 'noValidate',
  crossorigin: 'crossOrigin', enctype: 'encType', srcset: 'srcSet', inputmode: 'inputMode',
  enterkeyhint: 'enterKeyHint', playsinline: 'playsInline', autoplay: 'autoPlay',
  contenteditable: 'contentEditable', spellcheck: 'spellCheck', datetime: 'dateTime',
  frameborder: 'frameBorder', allowfullscreen: 'allowFullScreen', referrerpolicy: 'referrerPolicy',
  fetchpriority: 'fetchPriority', usemap: 'useMap', formaction: 'formAction',
  formnovalidate: 'formNoValidate', accesskey: 'accessKey', charset: 'charSet', hreflang: 'hrefLang',
  cellpadding: 'cellPadding', cellspacing: 'cellSpacing', 'xlink:href': 'xlinkHref',
  'xml:space': 'xmlSpace', 'xmlns:xlink': 'xmlnsXlink', 'xml:lang': 'xmlLang',
};
const URL_ATTRS = new Set(['src', 'href', 'srcset', 'poster', 'xlink:href']);
const NO_WS_CHILDREN = new Set(['table', 'thead', 'tbody', 'tfoot', 'tr', 'colgroup', 'select', 'optgroup']);
const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr']);

const camel = (s) => s.replace(/[-:]([a-z])/g, (m, c) => c.toUpperCase());
const HOLE_RE = /\{\{\s*([^{}]*?)\s*\}\}/g;
const IDENT = /^[A-Za-z_$][\w$]*$/;

function reactAttrName(name, isComponent) {
  if (name.startsWith('aria-') || name.startsWith('data-')) return name;
  if (isComponent) return camel(name);
  if (ATTR_MAP[name]) return ATTR_MAP[name];
  if (name.includes('-') || name.includes(':')) return camel(name);
  return name;
}

function cssCamel(prop) {
  if (prop.startsWith('--')) return prop;
  prop = prop.toLowerCase();
  if (prop.startsWith('-ms-')) prop = prop.slice(1);
  return prop.replace(/-([a-z])/g, (m, c) => c.toUpperCase());
}

function parseStyle(str) {
  const out = [];
  let depth = 0, quote = null, start = 0;
  const push = (decl) => {
    const i = decl.indexOf(':');
    if (i === -1) return;
    const k = decl.slice(0, i).trim();
    const val = decl.slice(i + 1).trim();
    if (k) out.push([cssCamel(k), rewriteBlobs(val)]);
  };
  for (let i = 0; i < str.length; i++) {
    const c = str[i];
    if (quote) { if (c === quote) quote = null; }
    else if (c === '"' || c === "'") quote = c;
    else if (c === '(') depth++;
    else if (c === ')') depth--;
    else if (c === ';' && depth === 0) { push(str.slice(start, i)); start = i + 1; }
  }
  push(str.slice(start));
  return out;
}

function makeCtx() {
  return { scopes: [], counter: 0, warnings: [] };
}

/** JS expression for a {{hole}}: dotted lookup into loop vars, $index or renderVals(). */
function holeExpr(expr, ctx) {
  expr = expr.trim();
  if (expr === 'true' || expr === 'false' || expr === 'null') return expr;
  if (/^-?\d+(\.\d+)?$/.test(expr)) return expr;
  if (/^'[^']*'$|^"[^"]*"$/.test(expr)) return JSON.stringify(expr.slice(1, -1));
  const parts = expr.split('.');
  if (!parts.every((p) => IDENT.test(p))) {
    ctx.warnings.push(`unsupported hole {{${expr}}}`);
    return 'undefined';
  }
  const [root, ...rest] = parts;
  let base;
  if (root === '$index') {
    const s = [...ctx.scopes].reverse()[0];
    base = s ? s.index : 'undefined';
  } else {
    const s = [...ctx.scopes].reverse().find((x) => x.as === root);
    base = s ? s.v : `v.${root}`;
  }
  return base + rest.map((p) => `?.${p}`).join('');
}

/** Splits a string with {{holes}}: one bare expression, or a template literal. */
function interp(str, ctx, wrapText) {
  const pieces = [];
  let last = 0;
  for (const m of str.matchAll(HOLE_RE)) {
    if (m.index > last) pieces.push({ lit: str.slice(last, m.index) });
    pieces.push({ expr: holeExpr(m[1], ctx) });
    last = m.index + m[0].length;
  }
  if (last < str.length) pieces.push({ lit: str.slice(last) });
  if (pieces.length === 1 && pieces[0].expr) return { whole: true, js: pieces[0].expr };
  const tl = pieces
    .map((p) => (p.lit != null ? p.lit.replace(/[`\\$]/g, (c) => '\\' + c) : '${' + wrapText(p.expr) + '}'))
    .join('');
  return { whole: false, js: '`' + tl + '`' };
}

function attrJsx(el, name, value, ctx, isComponent) {
  const hasHole = value.includes('{{');
  const lname = name.toLowerCase();
  let key = reactAttrName(name, isComponent);

  if (!isComponent && lname === 'style') {
    if (!hasHole) {
      const decls = parseStyle(value);
      if (!decls.length) return null;
      return `style={{${decls.map(([k, val]) => `${JSON.stringify(k)}: ${JSON.stringify(val)}`).join(', ')}}}`;
    }
    const r = interp(value, ctx, (e) => `T(${e})`);
    return `style={S(${r.js})}`;
  }

  if (!hasHole) {
    if (value === '' && BOOL_ATTRS.has(lname)) return `${key}`;
    let v = value;
    if (URL_ATTRS.has(lname)) v = rewriteBlobs(rewriteLinks(v));
    if (!isComponent && (el.name === 'input' || el.name === 'textarea') && lname === 'value') key = 'defaultValue';
    if (!isComponent && el.name === 'input' && lname === 'checked') key = 'defaultChecked';
    return `${key}=${JSON.stringify(v)}`;
  }

  const r = interp(value, ctx, (e) => `T(${e})`);
  let js = r.js;
  if (URL_ATTRS.has(lname)) js = `A(${js})`;
  return `${key}={${js}}`;
}

function textJsx(data, ctx, parentName) {
  if (!data.includes('{{')) {
    if (/^\s*$/.test(data)) {
      if (NO_WS_CHILDREN.has(parentName)) return '';
      return data.includes('\n') ? '{" "}' : `{${JSON.stringify(data)}}`;
    }
    return `{${JSON.stringify(data)}}`;
  }
  let out = '';
  let last = 0;
  for (const m of data.matchAll(HOLE_RE)) {
    if (m.index > last) out += `{${JSON.stringify(data.slice(last, m.index))}}`;
    out += `{T(${holeExpr(m[1], ctx)})}`;
    last = m.index + m[0].length;
  }
  if (last < data.length) out += `{${JSON.stringify(data.slice(last))}}`;
  return out;
}

const BLOCK = new Set([
  'div', 'section', 'header', 'footer', 'nav', 'main', 'article', 'aside', 'ul', 'ol', 'li', 'p',
  'h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'form', 'details', 'summary', 'table', 'thead', 'tbody', 'tr',
  'td', 'th', 'figure', 'figcaption', 'blockquote', 'dl', 'dt', 'dd', 'fieldset', 'hr', 'pre',
  'helmet', 'style', 'script', 'defs', 'g', 'path', 'circle', 'rect', 'line', 'polyline', 'polygon',
  'ellipse', 'stop', 'lineargradient', 'radialgradient', 'clippath', 'mask', 'filter', 'animate',
  'animatemotion', 'animatetransform', 'mpath', 'option', 'select', 'x-dc',
]);
const isWs = (n) => n && n.type === 'text' && /^\s*$/.test(n.data);
const isBlock = (n) => n && n.type === 'tag' && BLOCK.has(n.name);

function childrenJsx(node, ctx) {
  const kids = (node.children || []).filter((c) => c.type !== 'comment');
  return kids
    .map((c, i) => {
      // Whitespace HTML collapses away: indentation at an element's start or end,
      // and runs next to block-level elements.
      if (isWs(c)) {
        const prev = kids[i - 1], next = kids[i + 1];
        if (c.data.includes('\n') && (!prev || !next)) return '';
        if (isBlock(prev) || isBlock(next) || isBlock(node) && (!prev || !next)) return '';
      }
      return nodeJsx(c, ctx, node.name);
    })
    .join('');
}

function nodeJsx(node, ctx, parentName) {
  if (node.type === 'text') return textJsx(node.data, ctx, parentName);
  if (node.type === 'comment' || node.type === 'directive') return '';
  if (node.type !== 'tag' && node.type !== 'script' && node.type !== 'style') return '';
  const name = node.name;
  const attrs = node.attribs || {};

  if (name === 'helmet') return '';
  if (name === 'sc-if') {
    const cond = holeExpr((attrs.value || '').replace(/^\{\{|\}\}$/g, ''), ctx);
    return `{${cond} ? (<>${childrenJsx(node, ctx)}</>) : null}`;
  }
  if (name === 'sc-for') {
    const list = holeExpr((attrs.list || '').replace(/^\{\{|\}\}$/g, ''), ctx);
    const n = ctx.counter++;
    const scope = { as: attrs.as || 'item', v: `${(attrs.as || 'item').replace(/\W/g, '_')}_${n}`, index: `i_${n}` };
    ctx.scopes.push(scope);
    const body = childrenJsx(node, ctx);
    ctx.scopes.pop();
    return `{L(${list}).map((${scope.v}, ${scope.index}) => (<React.Fragment key={${scope.index}}>${body}</React.Fragment>))}`;
  }
  if (name === 'dc-import') {
    ctx.warnings.push('dc-import is not supported');
    return '';
  }

  let tag = name;
  let isComponent = false;
  if (name === 'x-import') {
    tag = attrs['component-from-global-scope'];
    isComponent = true;
    ctx.usesDs = true;
  }

  const parts = [];
  let hasOnChange = false;
  let onInput = null;
  for (const [k, v] of Object.entries(attrs)) {
    if (k.startsWith('hint-') || k === 'component-from-global-scope') continue;
    const a = attrJsx(node, k, v, ctx, isComponent);
    if (a == null) continue;
    if (/^onChange[={]/.test(a)) hasOnChange = true;
    if (/^onInput=/.test(a)) onInput = a.slice('onInput='.length);
    parts.push(a);
  }
  // Inputs the design binds with value + onInput become controlled React inputs.
  if (!isComponent && onInput && !hasOnChange && ['input', 'textarea', 'select'].includes(name)) {
    const i = parts.findIndex((p) => p.startsWith('onInput='));
    parts[i] = `onChange=${onInput}`;
  }
  // <option selected> -> <select defaultValue>.
  if (name === 'select') {
    const opts = (node.children || []).filter((c) => c.name === 'option');
    const sel = opts.find((o) => o.attribs && 'selected' in o.attribs && !String(o.attribs.selected).includes('{{'));
    if (sel && !('value' in attrs)) {
      const val = sel.attribs.value ?? sel.children.map((c) => c.data || '').join('');
      parts.push(`defaultValue=${JSON.stringify(val)}`);
    }
  }
  let a = parts.join(' ');
  if (name === 'option' && 'selected' in attrs && !String(attrs.selected).includes('{{')) {
    a = parts.filter((p) => p !== 'selected').join(' ');
  }

  if (name === 'style' || name === 'script') {
    const css = (node.children || []).map((c) => c.data || '').join('');
    return `<${tag} ${a} dangerouslySetInnerHTML={{ __html: ${JSON.stringify(rewriteBlobs(css))} }} />`;
  }
  if (name === 'textarea') {
    const txt = (node.children || []).map((c) => c.data || '').join('');
    if (txt.trim() && !txt.includes('{{')) return `<textarea ${a} defaultValue=${JSON.stringify(txt)} />`;
  }
  const kids = childrenJsx(node, ctx);
  if (!kids && (VOID.has(name) || !isComponent)) return `<${tag}${a ? ' ' + a : ''} />`;
  return `<${tag}${a ? ' ' + a : ''}>${kids}</${tag}>`;
}

// ---------------------------------------------------------------- per artboard
const findAll = (node, pred, out = []) => {
  for (const c of node.children || []) {
    if (pred(c)) out.push(c);
    findAll(c, pred, out);
  }
  return out;
};
const textOf = (n) => (n.children || []).map((c) => c.data || '').join('');

const pagesOut = path.join(ROOT, 'src/pages');
fs.rmSync(pagesOut, { recursive: true, force: true });
const prettierCfg = { parser: 'babel', printWidth: 110, singleQuote: true };
let warnings = 0;

for (const b of boards) {
  const raw = rewriteLinks(fs.readFileSync(path.join(projectDir, b.file), 'utf8'));
  const doc = parseDocument(raw, { recognizeSelfClosing: true, lowerCaseAttributeNames: false, lowerCaseTags: true });

  const xdc = findAll(doc, (n) => n.name === 'x-dc')[0];
  const helmet = findAll(xdc, (n) => n.name === 'helmet')[0];
  const script = findAll(doc, (n) => n.name === 'script' && n.attribs && 'data-dc-script' in n.attribs)[0];
  const title = textOf(findAll(doc, (n) => n.name === 'title')[0] || { children: [] }) || b.title;
  const lang = (findAll(doc, (n) => n.name === 'html')[0]?.attribs?.lang) || 'en';
  const headDs = findAll(doc, (n) => (n.name === 'link' || n.name === 'script') && /ds\/jobseeker/.test(n.attribs?.href || n.attribs?.src || ''));

  // Stylesheet and <head> links from <helmet>.
  const css = findAll(helmet, (n) => n.name === 'style').map(textOf).join('\n');
  const headLinks = findAll(helmet, (n) => n.name === 'link').map((l) => {
    const at = Object.entries(l.attribs).map(([k, v]) => (v === '' && k === 'crossorigin' ? k : `${k}="${v.replace(/&/g, '&amp;').replace(/"/g, '&quot;')}"`));
    return `    <link ${at.join(' ')}>`;
  });

  // Template -> JSX.
  const ctx = makeCtx();
  const body = childrenJsx(xdc, ctx);
  if (ctx.warnings.length) {
    warnings += ctx.warnings.length;
    console.warn(`${b.file}:`, [...new Set(ctx.warnings)].join('; '));
  }
  const usesDs = ctx.usesDs || headDs.length > 0;

  // Logic class, kept as the design wrote it.
  let logic = textOf(script).trim();
  if (!/class\s+Component\s+extends\s+DCLogic/.test(logic)) throw new Error(`${b.file}: no DCLogic class`);
  logic = rewriteLinks(logic);

  const header = [
    `// ${b.title}`,
    `// Generated from the design artboard ${b.file} by tools/convert-design.mjs.`,
    `import React from 'react';`,
    `import { DCLogic, A, L, S, T } from '../../lib/dc.js';`,
    usesDs ? `import Jobseeker from '../../ds/jobseeker/index.js';` : '',
    '',
  ].filter((l, i, arr) => l !== '' || i === arr.length - 1);
  const pageJs = [
    ...header,
    '',
    logic.replace(/class\s+Component\s+extends\s+DCLogic/, 'class Page extends DCLogic'),
    '',
    `Page.template = (v) => (<>${body}</>);`,
    '',
    'export default Page;',
    '',
  ].join('\n');

  const dir = path.join(pagesOut, b.name);
  fs.mkdirSync(dir, { recursive: true });
  let formatted;
  try {
    formatted = await prettier.format(pageJs, prettierCfg);
  } catch (e) {
    fs.writeFileSync(path.join(dir, 'Page.jsx'), pageJs);
    throw new Error(`${b.file}: generated JSX does not parse: ${e.message.split('\n')[0]}`);
  }
  fs.writeFileSync(path.join(dir, 'Page.jsx'), formatted);
  fs.writeFileSync(path.join(dir, 'styles.css'), `/* ${b.title} — from ${b.file} */\n` + rewriteBlobs(css).trim() + '\n');
  fs.writeFileSync(
    path.join(dir, 'main.jsx'),
    [
      usesDs ? `import '../../ds/jobseeker/styles.js';` : null,
      `import './styles.css';`,
      `import { mount } from '../../lib/mount.jsx';`,
      `import Page from './Page.jsx';`,
      '',
      'mount(Page);',
      '',
    ].filter((l) => l !== null).join('\n'),
  );

  const htmlDir = path.join(ROOT, b.route);
  fs.mkdirSync(htmlDir, { recursive: true });
  fs.writeFileSync(
    path.join(htmlDir, 'index.html'),
    `<!doctype html>
<html lang="${lang}">
  <head>
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <title>${title.replace(/&/g, '&amp;').replace(/</g, '&lt;')}</title>
    <link rel="icon" href="/favicon.svg" type="image/svg+xml">
${headLinks.join('\n')}
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="/src/pages/${b.name}/main.jsx"></script>
  </body>
</html>
`,
  );
}

fs.writeFileSync(
  path.join(ROOT, 'src/routes.json'),
  JSON.stringify(boards.map(({ name, route, title }) => ({ name, route, title })), null, 2) + '\n',
);
console.log(`Converted ${boards.length} pages, ${Object.keys(ASSETS).length} images` + (warnings ? `, ${warnings} warnings` : ''));
